def random_date() -> str:
    start = datetime(2025, 1, 1)
    delta = (datetime(2026, 12, 31) - start).days
    d = start + timedelta(days=random.randint(0, delta))
    return f"{d.day} {MONTHS_RU[d.month - 1]} {d.year}"


def generate_events(count: int = 1200):
    events = []
    for _ in range(count):
        category = random.choice(CATEGORIES)
        city = random.choice(CITIES)
        venue = random.choice(VENUES.get(category, ["Площадка"]))
        title_base = random.choice(TITLES.get(category, ["Мероприятие"]))
        title = f"{title_base}" if random.random() > 0.4 else f"{title_base} в {city}"
        image_url = random.choice(IMAGES.get(category, ["https://images.unsplash.com/photo-1540575467063-178f50002cbc?w=400&h=300&fit=crop"]))
        events.append(
            {
                "title": title,
                "date": random_date(),
                "location": f"{city}, {venue}",
                "description": random.choice(DESCRIPTIONS.get(category, ["Интересное мероприятие."])),
                "category": category,
                "image_url": image_url,
            }
        )
    return events


def seed():
    db = SessionLocal()
    try:
        existing = db.query(models.Event).count()
        if existing > 0:
            print(f"База данных уже содержит {existing} мероприятий. Пропускаем.")
            return
        print("Генерируем мероприятия...")
        data = generate_events(1200)
        for item in data:
            db.add(models.Event(**item))
        db.commit()
        print(f"Успешно добавлено {len(data)} мероприятий.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
